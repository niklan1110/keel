-- Scheduled jobs and outgoing HTTP requests from SQL, with the user-facing
-- API of pg_cron and pg_net (and the trigger function Supabase's Database
-- Webhooks create). Those extensions run their background worker in one
-- database per server, and every Keel project is a database of its own, so
-- keel-studio does the work instead: it runs due jobs and sends queued
-- requests for every project (server/src/studio/scheduler.ts).
--
-- Only the project's owner role (<database>_owner) and superusers may use
-- them, as on Supabase, where the API roles can't. Jobs run as the owner
-- role (a job scheduled by a superuser too), never as a superuser.

-- ---------------------------------------------------------------- cron

create schema if not exists cron;
revoke all on schema cron from public;

create table if not exists cron.job (
  jobid bigint generated by default as identity primary key,
  schedule text not null,
  command text not null,
  nodename text not null default 'localhost',
  nodeport int not null default 5432,
  database text not null default current_database(),
  username text not null default current_user,
  active boolean not null default true,
  jobname text,
  constraint jobname_username_uniq unique (jobname, username),
  -- keel-studio reads commands into memory: keep them to a sane size.
  constraint job_command_size check (octet_length(command) <= 1048576)
);

create table if not exists cron.job_run_details (
  jobid bigint,
  runid bigint generated by default as identity primary key,
  job_pid int,
  database text,
  username text,
  command text,
  status text,
  return_message text,
  start_time timestamptz,
  end_time timestamptz
);
create index if not exists job_run_details_jobid_idx on cron.job_run_details (jobid, start_time desc);
create index if not exists job_run_details_start_time_idx on cron.job_run_details (start_time);

-- Like pg_cron, each role sees and changes only its own jobs.
alter table cron.job enable row level security;
drop policy if exists cron_job_policy on cron.job;
create policy cron_job_policy on cron.job using (username = current_user) with check (username = current_user);
alter table cron.job_run_details enable row level security;
drop policy if exists cron_job_run_details_policy on cron.job_run_details;
create policy cron_job_run_details_policy on cron.job_run_details using (username = current_user);

-- The role a new job runs as: the caller, or the owner role when a superuser schedules it.
create or replace function cron._job_user() returns text
language sql stable set search_path = pg_catalog as $$
  select case when coalesce((select rolsuper from pg_roles where rolname = current_user), false)
              then current_database() || '_owner' else current_user::text end
$$;

-- A number or name in one field of a schedule (1 minute ... 5 day of week).
create or replace function cron._field_value(v text, field int) returns int
language plpgsql immutable set search_path = pg_catalog as $$
declare
  mins int[] := array[0, 0, 1, 1, 0];
  maxs int[] := array[59, 23, 31, 12, 7];
  months text[] := array['jan', 'feb', 'mar', 'apr', 'may', 'jun', 'jul', 'aug', 'sep', 'oct', 'nov', 'dec'];
  days text[] := array['sun', 'mon', 'tue', 'wed', 'thu', 'fri', 'sat'];
  n int;
begin
  if v ~ '^\d{1,2}$' then
    n := v::int;
    if n < mins[field] or n > maxs[field] then
      raise exception 'invalid schedule: % is out of range (%-%)', n, mins[field], maxs[field];
    end if;
    return n;
  end if;
  n := case field when 4 then array_position(months, v) when 5 then array_position(days, v) - 1 end;
  if n is null then
    raise exception 'invalid schedule: "%" is not valid', v;
  end if;
  return n;
end
$$;

-- Raises an error unless `schedule` is valid. The same rules as the scheduler's parser (server/src/lib/cron.ts).
create or replace function cron._check_schedule(schedule text) returns void
language plpgsql immutable set search_path = pg_catalog as $$
declare
  s text := lower(btrim(coalesce(schedule, '')));
  fields text[];
  item text;
  m text[];
  lo int;
  hi int;
begin
  if s ~ '^\d{1,2}\s+seconds?$' then
    if substring(s from '^\d+')::int not between 1 and 59 then
      raise exception 'invalid schedule: seconds must be from 1 to 59';
    end if;
    return;
  end if;
  s := case s
    when '@yearly' then '0 0 1 1 *' when '@annually' then '0 0 1 1 *' when '@monthly' then '0 0 1 * *'
    when '@weekly' then '0 0 * * 0' when '@daily' then '0 0 * * *' when '@midnight' then '0 0 * * *'
    when '@hourly' then '0 * * * *' else s end;
  if s like '@%' then
    raise exception 'invalid schedule: "%" is not supported', schedule;
  end if;
  fields := regexp_split_to_array(s, '\s+');
  if s = '' or array_length(fields, 1) <> 5 then
    raise exception 'invalid schedule: "%" (use 5 fields: minute hour day-of-month month day-of-week, or "N seconds")', schedule;
  end if;
  for i in 1..5 loop
    foreach item in array string_to_array(fields[i], ',') loop
      continue when i = 3 and item = '$';
      m := regexp_match(item, '^(\*|[a-z0-9]+|[a-z0-9]+-[a-z0-9]+)(?:/(\d{1,2}))?$');
      if m is null or (m[2] is not null and m[2]::int < 1) then
        raise exception 'invalid schedule: "%" is not valid', item;
      end if;
      if m[1] <> '*' then
        lo := cron._field_value(split_part(m[1], '-', 1), i);
        hi := case when m[1] like '%-%' then cron._field_value(split_part(m[1], '-', 2), i) else lo end;
        if hi < lo then
          raise exception 'invalid schedule: "%" runs backwards', item;
        end if;
      end if;
    end loop;
  end loop;
end
$$;

create or replace function cron.schedule(job_name text, schedule text, command text) returns bigint
language plpgsql set search_path = pg_catalog as $$
declare
  id bigint;
begin
  perform cron._check_schedule(schedule);
  if command is null then
    raise exception 'command must not be null';
  end if;
  if job_name is null then
    insert into cron.job (schedule, command, username) values (schedule, command, cron._job_user()) returning jobid into id;
  else
    -- Scheduling a name again replaces that job, as in pg_cron.
    insert into cron.job (schedule, command, username, jobname) values (schedule, command, cron._job_user(), job_name)
      on conflict (jobname, username) do update set schedule = excluded.schedule, command = excluded.command
      returning jobid into id;
  end if;
  return id;
end
$$;

create or replace function cron.schedule(schedule text, command text) returns bigint
language sql set search_path = pg_catalog as $$
  select cron.schedule(null::text, schedule, command)
$$;

create or replace function cron.schedule_in_database(job_name text, schedule text, command text, database text, username text default null, active boolean default true) returns bigint
language plpgsql set search_path = pg_catalog as $$
declare
  id bigint;
begin
  if database is distinct from current_database() then
    raise exception 'Keel runs jobs only in the database they are scheduled in (%)', current_database();
  end if;
  if username is not null and username <> cron._job_user() then
    raise exception 'jobs run as %', cron._job_user();
  end if;
  id := cron.schedule(job_name, schedule, command);
  update cron.job set active = coalesce(schedule_in_database.active, true) where jobid = id;
  return id;
end
$$;

create or replace function cron.unschedule(job_name text) returns boolean
language plpgsql set search_path = pg_catalog as $$
begin
  delete from cron.job where jobname = job_name and username = cron._job_user();
  if not found then
    raise exception 'could not find valid entry for job ''%''', job_name;
  end if;
  return true;
end
$$;

create or replace function cron.unschedule(job_id bigint) returns boolean
language plpgsql set search_path = pg_catalog as $$
begin
  delete from cron.job where jobid = job_id;
  if not found then
    raise exception 'could not find valid entry for job %', job_id;
  end if;
  return true;
end
$$;

create or replace function cron.alter_job(job_id bigint, schedule text default null, command text default null, database text default null, username text default null, active boolean default null) returns void
language plpgsql set search_path = pg_catalog as $$
begin
  if schedule is not null then
    perform cron._check_schedule(schedule);
  end if;
  if database is not null and database <> current_database() then
    raise exception 'Keel runs jobs only in the database they are scheduled in (%)', current_database();
  end if;
  update cron.job j
     set schedule = coalesce(alter_job.schedule, j.schedule),
         command = coalesce(alter_job.command, j.command),
         active = coalesce(alter_job.active, j.active)
   where j.jobid = job_id;
  if not found then
    raise exception 'Job % does not exist or you don''t own it', job_id;
  end if;
  if username is not null and username <> (select j.username from cron.job j where j.jobid = job_id) then
    raise exception 'a job''s user can''t be changed';
  end if;
end
$$;

-- ---------------------------------------------------------------- net (pg_net)

create schema if not exists net;
revoke all on schema net from public;

do $$
begin
  if not exists (select 1 from pg_type where typname = 'http_method' and typnamespace = 'net'::regnamespace) then
    create domain net.http_method as text check (value in ('GET', 'POST', 'DELETE'));
  end if;
end
$$;

create table if not exists net.http_request_queue (
  id bigserial primary key,
  method net.http_method not null,
  url text not null,
  headers jsonb,
  body bytea,
  timeout_milliseconds int not null,
  -- keel-studio holds requests in memory while it sends them.
  constraint http_request_size check (octet_length(url) <= 32768 and pg_column_size(headers) <= 65536 and coalesce(octet_length(body), 0) <= 5242880)
);

create table if not exists net._http_response (
  id bigint,
  status_code integer,
  content_type text,
  headers jsonb,
  content text,
  timed_out bool,
  error_msg text,
  created timestamptz not null default now()
);
create index if not exists _http_response_id_idx on net._http_response (id);
create index if not exists _http_response_created_idx on net._http_response (created);

-- encodeURIComponent for query parameters.
create or replace function net._urlencode(s text) returns text
language sql immutable strict set search_path = pg_catalog as $$
  select coalesce(string_agg(
           case when b between 48 and 57 or b between 65 and 90 or b between 97 and 122 or b in (45, 46, 95, 126)
                then chr(b) else '%' || upper(lpad(to_hex(b), 2, '0')) end, '' order by i), '')
    from (select i, get_byte(convert_to(s, 'UTF8'), i) as b
            from generate_series(0, octet_length(convert_to(s, 'UTF8')) - 1) as i) x
$$;

-- Queues a request; keel-studio sends it after the transaction commits.
create or replace function net._enqueue(method text, url text, params jsonb, headers jsonb, body bytea, timeout_milliseconds int) returns bigint
language plpgsql set search_path = pg_catalog as $$
declare
  full_url text := url;
  query text;
  id bigint;
begin
  if url is null or url !~* '^https?://' then
    raise exception 'net: only http and https URLs are supported';
  end if;
  if headers is not null and jsonb_typeof(headers) <> 'object' then
    raise exception 'net: headers must be a JSON object';
  end if;
  if params is not null and jsonb_typeof(params) <> 'object' then
    raise exception 'net: params must be a JSON object';
  end if;
  if timeout_milliseconds is null or timeout_milliseconds < 1 then
    raise exception 'net: timeout_milliseconds must be positive';
  end if;
  select string_agg(net._urlencode(key) || '=' || net._urlencode(value), '&') into query
    from jsonb_each_text(coalesce(params, '{}'::jsonb));
  if query is not null then
    full_url := full_url || case when position('?' in full_url) > 0 then '&' else '?' end || query;
  end if;
  -- Nothing sends requests while keel-studio is down; don't pile up without end.
  if (select count(*) from (select 1 from net.http_request_queue limit 10000) q) >= 10000 then
    raise exception 'net: 10000 requests are already waiting to be sent';
  end if;
  insert into net.http_request_queue (method, url, headers, body, timeout_milliseconds)
    values (method, full_url, coalesce(headers, '{}'::jsonb), body, timeout_milliseconds)
    returning http_request_queue.id into id;
  return id;
end
$$;

create or replace function net.http_get(url text, params jsonb default '{}'::jsonb, headers jsonb default '{}'::jsonb, timeout_milliseconds int default 5000) returns bigint
language sql set search_path = pg_catalog as $$
  select net._enqueue('GET', url, params, headers, null, timeout_milliseconds)
$$;

create or replace function net.http_post(url text, body jsonb default '{}'::jsonb, params jsonb default '{}'::jsonb, headers jsonb default '{"Content-Type": "application/json"}'::jsonb, timeout_milliseconds int default 5000) returns bigint
language sql set search_path = pg_catalog as $$
  select net._enqueue('POST', url, params, headers, convert_to(body::text, 'UTF8'), timeout_milliseconds)
$$;

create or replace function net.http_delete(url text, params jsonb default '{}'::jsonb, headers jsonb default '{}'::jsonb, timeout_milliseconds int default 5000, body jsonb default null) returns bigint
language sql set search_path = pg_catalog as $$
  select net._enqueue('DELETE', url, params, headers, case when body is null then null else convert_to(body::text, 'UTF8') end, timeout_milliseconds)
$$;

-- ---------------------------------------------------------------- Database Webhooks

create schema if not exists supabase_functions;
revoke all on schema supabase_functions from public;

create table if not exists supabase_functions.hooks (
  id bigserial primary key,
  hook_table_id integer not null,
  hook_name text not null,
  created_at timestamptz not null default now(),
  request_id bigint
);
create index if not exists supabase_functions_hooks_request_id_idx on supabase_functions.hooks (request_id);
create index if not exists supabase_functions_hooks_h_table_id_h_name_idx on supabase_functions.hooks (hook_table_id, hook_name);

-- The trigger function Supabase's Database Webhooks use:
--   create trigger ... execute function supabase_functions.http_request(
--     'https://...', 'POST', '{"Content-Type":"application/json"}', '{}', '1000');
-- It runs as the owner role (security definer), so a change made through the
-- API (as anon or authenticated) can queue the request.
create or replace function supabase_functions.http_request() returns trigger
language plpgsql security definer set search_path = pg_catalog as $$
declare
  request_id bigint;
  payload jsonb;
  url text := tg_argv[0]::text;
  method text := tg_argv[1]::text;
  headers jsonb default '{}'::jsonb;
  params jsonb default '{}'::jsonb;
  timeout_ms integer default 1000;
begin
  if url is null or url = 'null' then
    raise exception 'url argument is missing';
  end if;
  if method is null or method = 'null' then
    raise exception 'method argument is missing';
  end if;
  if tg_argv[2] is null or tg_argv[2] = 'null' then
    headers := '{"Content-Type": "application/json"}'::jsonb;
  else
    headers := tg_argv[2]::jsonb;
  end if;
  if tg_argv[3] is null or tg_argv[3] = 'null' then
    params := '{}'::jsonb;
  else
    params := tg_argv[3]::jsonb;
  end if;
  if tg_argv[4] is null or tg_argv[4] = 'null' then
    timeout_ms := 1000;
  else
    timeout_ms := tg_argv[4]::integer;
  end if;
  case
    when method = 'GET' then
      request_id := net.http_get(url, params, headers, timeout_ms);
    when method = 'POST' then
      payload := jsonb_build_object('old_record', old, 'record', new, 'type', tg_op, 'table', tg_table_name, 'schema', tg_table_schema);
      request_id := net.http_post(url, payload, params, headers, timeout_ms);
    else
      raise exception 'method argument % is invalid', method;
  end case;
  insert into supabase_functions.hooks (hook_table_id, hook_name, request_id) values (tg_relid, tg_name, request_id);
  return new;
end
$$;

