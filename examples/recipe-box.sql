-- Example schema: a small recipe app with per-user meal plans.
-- Load it into a project with:
--   ./keel psql recipe-box < examples/recipe-box.sql
-- or paste it into Studio's SQL editor.

create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  display_name text,
  household int2,
  created_at timestamptz not null default now()
);

create table if not exists public.recipes (
  id bigint generated by default as identity primary key,
  title text not null,
  servings int4,
  prep_min int4,
  is_public bool not null default false,
  author_id uuid references public.profiles (id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.ingredients (
  id bigint generated by default as identity primary key,
  name text not null unique,
  unit text,
  category text
);

create table if not exists public.recipe_ingredients (
  recipe_id bigint not null references public.recipes (id) on delete cascade,
  ingredient_id bigint not null references public.ingredients (id) on delete restrict,
  quantity numeric,
  note text,
  primary key (recipe_id, ingredient_id)
);

create table if not exists public.tags (
  id int4 generated by default as identity primary key,
  slug text not null unique,
  label text not null
);

create table if not exists public.meal_plans (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references public.profiles (id) on delete cascade,
  week_of date not null,
  recipe_ids int8[] not null default '{}',
  shared bool not null default false
);

-- Policies: public recipes are readable by anyone, everything else is private.
drop policy if exists "Public recipes are readable" on public.recipes;
create policy "Public recipes are readable" on public.recipes for select using (is_public or author_id = auth.uid());
drop policy if exists "Authors manage their recipes" on public.recipes;
create policy "Authors manage their recipes" on public.recipes for all to authenticated
  using (author_id = auth.uid()) with check (author_id = auth.uid());

drop policy if exists "Ingredients are readable" on public.ingredients;
create policy "Ingredients are readable" on public.ingredients for select using (true);
drop policy if exists "Recipe ingredients are readable" on public.recipe_ingredients;
create policy "Recipe ingredients are readable" on public.recipe_ingredients for select using (true);
drop policy if exists "Tags are readable" on public.tags;
create policy "Tags are readable" on public.tags for select using (true);

drop policy if exists "Profiles are readable" on public.profiles;
create policy "Profiles are readable" on public.profiles for select using (true);
drop policy if exists "Users edit their profile" on public.profiles;
create policy "Users edit their profile" on public.profiles for update to authenticated
  using (id = auth.uid()) with check (id = auth.uid());

drop policy if exists "Own or shared meal plans" on public.meal_plans;
create policy "Own or shared meal plans" on public.meal_plans for select to authenticated using (profile_id = auth.uid() or shared);
drop policy if exists "Users manage their meal plans" on public.meal_plans;
create policy "Users manage their meal plans" on public.meal_plans for all to authenticated
  using (profile_id = auth.uid()) with check (profile_id = auth.uid());

-- Create a profile row whenever someone signs up.
create or replace function public.handle_new_user() returns trigger
language plpgsql security definer set search_path = public as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(new.raw_user_meta_data ->> 'full_name', split_part(new.email, '@', 1)))
  on conflict (id) do nothing;
  return new;
end
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

-- Stream meal plan changes to subscribed clients.
do $$ begin
  if not exists (select 1 from pg_publication_tables where pubname = 'supabase_realtime' and tablename = 'meal_plans') then
    alter publication supabase_realtime add table public.meal_plans;
  end if;
end $$;

